#!/bin/sh
# Vendors AFFiNE's edgeless templates and stickers (MIT) into the SPA.
#
# Source: https://github.com/toeverything/AFFiNE, packages/frontend/templates.
# That directory is under AFFiNE's MIT terms (only packages/backend and
# packages/common/native are not). Nothing from those two directories is used.
#
# Output (committed):
#   web/vendor/affine-templates/   sticker SVGs, generated template JSON, the
#                                  *.gen.ts registries, LICENSE-MIT, README.md
#   web/public/static/templates/   images referenced by the board templates
#
# usage: scripts/vendor-affine-templates.sh [commit]   (run from web/)
set -eu
COMMIT="${1:-91ac3ca384b791ffd1a87de352a82e766f11ae08}"
WEB="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$WORK"
git init -q src
cd src
git remote add origin https://github.com/toeverything/AFFiNE.git
git sparse-checkout set --no-cone /packages/frontend/templates/ /LICENSE-MIT >/dev/null
git fetch -q --depth 1 --filter=blob:none origin "$COMMIT"
git checkout -q FETCH_HEAD

T=packages/frontend/templates
mkdir -p packages/frontend/core/public/static/templates
# build-edgeless.mjs unpacks the snapshot zips into edgeless/*.json and their
# images into ../core/public/static/templates; it needs jszip only.
(cd "$T" && npm i --no-save --ignore-scripts --silent jszip@3.10.1 && node build-edgeless.mjs)

OUT="$WEB/vendor/affine-templates"
rm -rf "$OUT" "$WEB/public/static/templates"
mkdir -p "$OUT" "$WEB/public/static"
cp -R "$T/stickers" "$T/edgeless" "$OUT/"
cp "$T/stickers-templates.gen.ts" "$T/edgeless-templates.gen.ts" LICENSE-MIT "$OUT/"
cp -R packages/frontend/core/public/static/templates "$WEB/public/static/templates"
find "$OUT" "$WEB/public/static/templates" -name .DS_Store -delete

cat > "$OUT/README.md" <<MD
# AFFiNE edgeless templates and stickers (vendored)

Copied from [toeverything/AFFiNE](https://github.com/toeverything/AFFiNE) at
commit \`$COMMIT\`, directory \`packages/frontend/templates\`, under the MIT
license in \`LICENSE-MIT\` (Copyright (c) TOEVERYTHING PTE. LTD. and its
affiliates). \`edgeless/*.json\` and the board-template images in
\`web/public/static/templates\` were generated by that directory's
\`build-edgeless.mjs\` from its \`edgeless-snapshot/*.zip\`; everything else is
copied unchanged. Regenerate with \`web/scripts/vendor-affine-templates.sh\`.
MD
echo "vendored AFFiNE templates at $COMMIT"
